#!/usr/bin/env node
// Generates editor/agent artifacts from languages.json:
//   editors/vscode/syntaxes/wreak.tmLanguage.json   (TextMate grammar)
//   editors/vscode/package.json                     (embeddedLanguages map)
//   editors/vim/autoload/wreak/languages.vim        (alias -> filetype map)
//   skill/wreak/scripts/languages.json              (alias -> canonical id)
//   skill/wreak/references/spec.md                  (copy of docs/spec.md)
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => JSON.parse(readFileSync(join(root, p), "utf8"));
const write = (p, s) => {
  writeFileSync(join(root, p), s);
  console.log(`wrote ${p}`);
};

const { languages } = read("languages.json");

// ---------------------------------------------------------------- shared regex
const HEADER_END = "(?=\\s|$)";
const reEscape = (s) => s.replace(/[.*+?^${}()|[\]\\#-]/g, "\\$&");
const names = (lang) => [lang.id, ...lang.aliases];
// Matches `--language NAME`, `--language=NAME` or `-l NAME` somewhere after the colon.
const languageFlag = (alts) =>
  `(?=(?:.*\\s)?(?:--language(?:\\s+|=)|-l\\s+)(?:${alts})(?=\\s|$))`;
// A block continues while lines are blank or start with whitespace.
const WHILE = "^(?!\\S)";

const headerCaptures = (family) => ({
  1: { name: `keyword.control.block.${family}.wreak` },
  2: { name: "punctuation.separator.block.wreak" },
  3: { patterns: [{ include: "#header-flags" }] },
});

// ---------------------------------------------------------------- TextMate
const embeddedBlocks = languages.map((lang) => ({
  name: `meta.block.code.${lang.id}.wreak`,
  begin: `^(code)(:)${HEADER_END}${languageFlag(names(lang).map(reEscape).join("|"))}(.*)$`,
  beginCaptures: headerCaptures("code"),
  while: WHILE,
  contentName: `meta.embedded.block.${lang.id}`,
  patterns: [{ include: lang.scope }],
}));

const grammar = {
  $schema: "https://raw.githubusercontent.com/martinring/tmlanguage/master/tmlanguage.json",
  name: "Wreak",
  scopeName: "source.wreak",
  fileTypes: ["wreak"],
  comment: "GENERATED by scripts/build.mjs from languages.json. Do not edit by hand.",
  patterns: [
    { include: "#comment" },
    { include: "#code-block-embedded" },
    { include: "#code-block" },
    { include: "#pseudo-code-block" },
    { include: "#text-block" },
    { include: "#stray" },
  ],
  repository: {
    comment: { match: "^#.*$", name: "comment.line.number-sign.wreak" },

    stray: {
      comment: "Column-0 prose outside any block is treated as implicit text.",
      match: "^\\S.*$",
      name: "meta.block.text.wreak meta.stray.wreak",
    },

    "header-flags": {
      patterns: [
        {
          match: "(?<=\\s|^)(--?[A-Za-z][\\w-]*)(?:(=)|\\s+)?(?:(?<=[=\\s])([^\\s-]\\S*))?",
          captures: {
            1: { name: "variable.parameter.flag.wreak" },
            2: { name: "keyword.operator.assignment.wreak" },
            3: { name: "string.unquoted.flag-value.wreak" },
          },
        },
      ],
    },

    "code-block-embedded": { patterns: embeddedBlocks },

    "code-block": {
      comment: "code: with no (or an unknown) --language gets generic highlighting.",
      name: "meta.block.code.wreak",
      begin: `^(code)(:)${HEADER_END}(.*)$`,
      beginCaptures: headerCaptures("code"),
      while: WHILE,
      contentName: "markup.raw.block.code.wreak",
      patterns: [{ include: "#generic-code" }],
    },

    "generic-code": {
      patterns: [
        { begin: "/\\*", end: "\\*/", name: "comment.block.code.wreak" },
        { match: "(?://|#|--(?=\\s)).*$", name: "comment.line.code.wreak" },
        { match: "\"(?:[^\"\\\\]|\\\\.)*\"|'(?:[^'\\\\]|\\\\.)*'|`[^`]*`", name: "string.quoted.code.wreak" },
        { match: "\\b(?:0x[\\da-fA-F]+|\\d+(?:\\.\\d+)?)\\b", name: "constant.numeric.code.wreak" },
      ],
    },

    "pseudo-code-block": {
      name: "meta.block.pseudo-code.wreak",
      begin: `^(pseudo-?code)(:)${HEADER_END}(.*)$`,
      beginCaptures: headerCaptures("pseudo-code"),
      while: WHILE,
      contentName: "meta.body.pseudo-code.wreak",
      patterns: [{ include: "#pseudo-code" }],
    },

    "pseudo-code": {
      patterns: [
        { match: "(?://|#).*$", name: "comment.line.pseudo.wreak" },
        { match: "\"(?:[^\"\\\\]|\\\\.)*\"|'(?:[^'\\\\]|\\\\.)*'", name: "string.quoted.pseudo.wreak" },
        { match: "\\b\\d+(?:\\.\\d+)?\\b", name: "constant.numeric.pseudo.wreak" },
        {
          match: "\\b(?i:true|false|null|nil|none|undefined)\\b",
          name: "constant.language.pseudo.wreak",
        },
        {
          match:
            "\\b(?i:if|else|elif|elseif|then|end|endif|for|foreach|each|in|of|while|do|until|repeat|loop|return|returns|break|continue|function|func|fn|def|procedure|proc|method|class|struct|type|interface|trait|enum|module|import|from|export|let|var|const|set|call|new|try|catch|except|finally|throw|raise|match|case|when|switch|default|async|await|yield|and|or|not|is|with|as|given|on|emit)\\b",
          name: "keyword.control.pseudo.wreak",
        },
        { match: "\\b[A-Za-z_][\\w]*(?=\\s*\\()", name: "entity.name.function.pseudo.wreak" },
        { match: "\\b[A-Z][A-Za-z0-9_]*\\b", name: "entity.name.type.pseudo.wreak" },
        { match: "<-|->|=>|:=|==|!=|<=|>=|&&|\\|\\||[+\\-*/%=<>!]", name: "keyword.operator.pseudo.wreak" },
      ],
    },

    "text-block": {
      name: "meta.block.text.wreak",
      begin: `^(text)(:)${HEADER_END}(.*)$`,
      beginCaptures: headerCaptures("text"),
      while: WHILE,
      contentName: "meta.body.text.wreak",
      patterns: [{ include: "#text" }],
    },

    text: {
      patterns: [
        { match: "`[^`]+`", name: "markup.inline.raw.text.wreak" },
        { match: "\\*\\*[^*]+\\*\\*", name: "markup.bold.text.wreak" },
        {
          match: "\\b(?:MUST NOT|MUST|SHOULD NOT|SHOULD|NEVER|ALWAYS|DO NOT|DON'T|REQUIRED|OPTIONAL)\\b",
          name: "keyword.other.requirement.text.wreak",
        },
      ],
    },
  },
};

write("editors/vscode/syntaxes/wreak.tmLanguage.json", JSON.stringify(grammar, null, 2) + "\n");

// ---------------------------------------------------------------- VS Code manifest
const pkgPath = "editors/vscode/package.json";
const pkg = read(pkgPath);
const embedded = Object.fromEntries(
  languages.map((l) => [`meta.embedded.block.${l.id}`, l.vscodeId]),
);
pkg.contributes.grammars[0].embeddedLanguages = embedded;
write(pkgPath, JSON.stringify(pkg, null, 2) + "\n");

// ---------------------------------------------------------------- Vim
const vimEntries = languages
  .flatMap((l) => names(l).map((n) => `\\ '${n}': '${l.vim}',`))
  .join("\n");
write(
  "editors/vim/autoload/wreak/languages.vim",
  `" GENERATED by scripts/build.mjs from languages.json. Do not edit by hand.
" Maps a \`--language\` name/alias to a Vim filetype. Extend or override with
" g:wreak_language_map in your vimrc/init.lua.
function! wreak#languages#map() abort
  return {
${vimEntries}
\\ }
endfunction
`,
);

// ---------------------------------------------------------------- Agent skill
const aliasMap = Object.fromEntries(
  languages.flatMap((l) => names(l).map((n) => [n, l.id])),
);
write("skill/wreak/scripts/languages.json", JSON.stringify(aliasMap, null, 2) + "\n");

// The skill ships its own copy of the spec so it is self-contained when installed.
write(
  "skill/wreak/references/spec.md",
  readFileSync(join(root, "docs/spec.md"), "utf8").replace("(../languages.json)", "(../scripts/languages.json)"),
);
